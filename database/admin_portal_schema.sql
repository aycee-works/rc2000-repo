-- Admin portal tables live in their own PostgreSQL schema.
CREATE SCHEMA IF NOT EXISTS rc2000_admin;
SET search_path TO rc2000_admin, public;
-- ============================================================
-- Reading Club 2000 - Canonical database schema (PostgreSQL 13+)
--
-- HOW TO RUN (pgAdmin):
--   1. Right-click "Databases" > Create > Database... > name: rc2000_db
--      (Definition tab: Encoding UTF8). Click Save.
--   2. Select that database, open Tools > Query Tool, open this file
--      (folder icon) and run it with the Execute (play) button.
--   Safe to run again: everything uses IF NOT EXISTS / OR REPLACE.
--
-- Timezone strategy: every timestamp is TIMESTAMPTZ (an exact moment in time),
-- and the PHP connection sets the session time zone to Asia/Manila
-- (see config/database.php), so times are shown in Philippine time.
-- Any other site that connects (e.g. the public website) gets correct
-- instants automatically, whatever its own time zone is.
--
-- SCHEMA CHANGE LOG
--   v1 - initial schema (MySQL/MariaDB)
--   v2 - ported to PostgreSQL: IDENTITY ids, CHECK constraints instead of ENUM,
--        BOOLEAN, TIMESTAMPTZ, and a trigger that keeps updated_at current.
-- ============================================================

-- Keeps updated_at current when a row changes (used by the triggers below).
-- The edit-conflict check in the admin pages relies on this column.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------
-- Administrator accounts (created only by database/create-admin.php
-- or by a super admin; there is NO public registration)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admins (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'admin'
                  CONSTRAINT chk_admins_role CHECK (role IN ('super_admin', 'admin')),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ  NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- Emails are unique ignoring upper/lower case
CREATE UNIQUE INDEX IF NOT EXISTS uq_admins_email ON admins (lower(email));

-- Failed login attempts (used to slow down password guessing)
CREATE TABLE IF NOT EXISTS login_attempts (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(150) NOT NULL,
    ip_address   VARCHAR(45)  NOT NULL,
    attempted_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_attempts_email ON login_attempts (email, attempted_at);
CREATE INDEX IF NOT EXISTS idx_attempts_ip    ON login_attempts (ip_address, attempted_at);

-- ------------------------------------------------------------
-- Book donations (submitted by the public site)
-- qty_offered is what the donor declared and is never overwritten.
-- qty_received is set by the admin after physically receiving books.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS book_donations (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no    VARCHAR(20)  NULL,                 -- e.g. BD-0001
    idempotency_key VARCHAR(64)  NULL,                 -- optional, stops double submissions
    donor_name      VARCHAR(120) NOT NULL,
    donor_email     VARCHAR(150) NOT NULL,
    donor_contact   VARCHAR(30)  NULL,
    book_title      VARCHAR(200) NOT NULL,
    author          VARCHAR(150) NULL,
    genre           VARCHAR(60)  NULL,
    book_condition  VARCHAR(10)  NOT NULL DEFAULT 'Good'
                    CONSTRAINT chk_book_condition CHECK (book_condition IN ('Excellent', 'Good', 'Fair', 'Poor')),
    qty_offered     INTEGER      NOT NULL CONSTRAINT chk_book_qty_offered CHECK (qty_offered > 0),
    qty_received    INTEGER      NULL     CONSTRAINT chk_book_qty_received CHECK (qty_received >= 0),
    notes           TEXT         NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'pending'
                    CONSTRAINT chk_book_status CHECK (status IN ('pending', 'approved', 'rejected')),
    reviewed_by     INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    reviewed_at     TIMESTAMPTZ  NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_book_ref  UNIQUE (reference_no),
    CONSTRAINT uq_book_idem UNIQUE (idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_book_status  ON book_donations (status);
CREATE INDEX IF NOT EXISTS idx_book_email   ON book_donations (donor_email);
CREATE INDEX IF NOT EXISTS idx_book_created ON book_donations (created_at);

-- ------------------------------------------------------------
-- Monetary donations (reports submitted by the public site)
-- reported_amount = what the donor says they sent (never overwritten)
-- verified_amount = what the admin confirmed (NULL until verified)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS monetary_donations (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no      VARCHAR(20)   NULL,              -- e.g. MD-0001 (the "Ticket No.")
    idempotency_key   VARCHAR(64)   NULL,
    donor_name        VARCHAR(120)  NOT NULL,
    donor_email       VARCHAR(150)  NOT NULL,
    donor_contact     VARCHAR(30)   NULL,
    reported_amount   NUMERIC(12,2) NOT NULL CONSTRAINT chk_money_reported CHECK (reported_amount > 0),
    payment_method    VARCHAR(40)   NULL,              -- Bank transfer, E-wallet, ...
    transaction_ref   VARCHAR(100)  NULL,
    proof_path        VARCHAR(255)  NULL,              -- private file under uploads/proofs/
    status            VARCHAR(20)   NOT NULL DEFAULT 'pending'
                      CONSTRAINT chk_money_status CHECK (status IN ('pending', 'verified', 'not_verified')),
    verified_amount   NUMERIC(12,2) NULL CONSTRAINT chk_money_verified CHECK (verified_amount IS NULL OR verified_amount >= 0),
    verification_note VARCHAR(255)  NULL,
    verified_by       INTEGER       NULL REFERENCES admins(id) ON DELETE SET NULL,
    verified_at       TIMESTAMPTZ   NULL,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_money_ref  UNIQUE (reference_no),
    CONSTRAINT uq_money_idem UNIQUE (idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_money_status  ON monetary_donations (status);
CREATE INDEX IF NOT EXISTS idx_money_email   ON monetary_donations (donor_email);
CREATE INDEX IF NOT EXISTS idx_money_created ON monetary_donations (created_at);

-- ------------------------------------------------------------
-- Inquiries (submitted by the public site)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inquiries (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no     VARCHAR(20)  NULL,                -- e.g. INQ-0001
    idempotency_key  VARCHAR(64)  NULL,
    name             VARCHAR(120) NOT NULL,
    email            VARCHAR(150) NOT NULL,
    subject          VARCHAR(200) NOT NULL,
    category         VARCHAR(20)  NOT NULL DEFAULT 'Inquiry'
                     CONSTRAINT chk_inq_category CHECK (category IN ('Request', 'Technical', 'Report', 'Inquiry')),
    message          TEXT         NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'open'
                     CONSTRAINT chk_inq_status CHECK (status IN ('open', 'in_progress', 'resolved', 'closed')),
    resolution_notes TEXT         NULL,
    resolved_by      INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    resolved_at      TIMESTAMPTZ  NULL,
    closed_by        INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    closed_at        TIMESTAMPTZ  NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_inq_ref  UNIQUE (reference_no),
    CONSTRAINT uq_inq_idem UNIQUE (idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_inq_status   ON inquiries (status);
CREATE INDEX IF NOT EXISTS idx_inq_category ON inquiries (category);
CREATE INDEX IF NOT EXISTS idx_inq_created  ON inquiries (created_at);

-- Saved admin responses. "Mark resolved" is only allowed when at least one
-- row exists here for the inquiry (checked in PHP).
-- email_status stays 'not_configured' until SMTP is set up, so we never
-- claim an email was sent when it was not.
CREATE TABLE IF NOT EXISTS inquiry_responses (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id   INTEGER     NOT NULL REFERENCES inquiries(id) ON DELETE CASCADE,
    admin_id     INTEGER     NULL REFERENCES admins(id) ON DELETE SET NULL,
    body         TEXT        NOT NULL,
    email_status VARCHAR(20) NOT NULL DEFAULT 'not_configured'
                 CONSTRAINT chk_resp_email_status CHECK (email_status IN ('not_configured', 'pending', 'sent', 'failed')),
    emailed_at   TIMESTAMPTZ NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_resp_inquiry ON inquiry_responses (inquiry_id);

-- ------------------------------------------------------------
-- Content shown on the public website
-- status: draft = hidden, published = visible, archived = hidden
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gallery_images (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(150) NOT NULL,
    caption       VARCHAR(255) NULL,
    file_path     VARCHAR(255) NOT NULL,               -- relative, e.g. uploads/gallery/abc.jpg
    original_name VARCHAR(255) NULL,
    mime_type     VARCHAR(50)  NULL,
    file_size     INTEGER      NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'draft'
                  CONSTRAINT chk_gallery_status CHECK (status IN ('draft', 'published', 'archived')),
    sort_order    INTEGER      NOT NULL DEFAULT 0,
    created_by    INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_gallery_status ON gallery_images (status, sort_order);

-- Stories and articles share one table; `type` keeps them distinguishable.
CREATE TABLE IF NOT EXISTS stories (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(10)  NOT NULL DEFAULT 'story'
                 CONSTRAINT chk_stories_type CHECK (type IN ('story', 'article')),
    title        VARCHAR(200) NOT NULL,
    body         TEXT         NOT NULL,
    author       VARCHAR(120) NULL,
    cover_path   VARCHAR(255) NULL,
    status       VARCHAR(20)  NOT NULL DEFAULT 'draft'
                 CONSTRAINT chk_stories_status CHECK (status IN ('draft', 'published', 'archived')),
    published_at TIMESTAMPTZ  NULL,
    created_by   INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_stories_status ON stories (type, status, published_at);

CREATE TABLE IF NOT EXISTS announcements (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    body         TEXT         NOT NULL,
    image_path   VARCHAR(255) NULL,
    status       VARCHAR(20)  NOT NULL DEFAULT 'draft'
                 CONSTRAINT chk_ann_status CHECK (status IN ('draft', 'published', 'archived')),
    published_at TIMESTAMPTZ  NULL,
    created_by   INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ann_status ON announcements (status, published_at);

CREATE TABLE IF NOT EXISTS trivia (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question    VARCHAR(255) NOT NULL,
    answer      VARCHAR(255) NOT NULL,
    explanation TEXT         NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'draft'
                CONSTRAINT chk_trivia_status CHECK (status IN ('draft', 'published')),
    created_by  INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_trivia_status ON trivia (status);

-- ------------------------------------------------------------
-- Audit trail of administrator actions
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activity_logs (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    action      VARCHAR(60)  NOT NULL,                 -- e.g. login, book_donation_updated
    entity_type VARCHAR(40)  NULL,                     -- e.g. book_donation
    entity_id   INTEGER      NULL,
    details     VARCHAR(500) NULL,
    ip_address  VARCHAR(45)  NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_log_admin   ON activity_logs (admin_id);
CREATE INDEX IF NOT EXISTS idx_log_entity  ON activity_logs (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_log_created ON activity_logs (created_at);

-- ------------------------------------------------------------
-- Triggers: refresh updated_at whenever a row actually changes
-- ------------------------------------------------------------
DROP TRIGGER IF EXISTS trg_admins_updated ON admins;
CREATE TRIGGER trg_admins_updated BEFORE UPDATE ON admins
    FOR EACH ROW WHEN (OLD.* IS DISTINCT FROM NEW.*) EXECUTE FUNCTION set_updated_at();

