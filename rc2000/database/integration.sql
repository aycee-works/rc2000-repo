-- Reference-number counters: BD-0001, MD-0001, INQ-0001 ...
CREATE SEQUENCE IF NOT EXISTS book_donation_seq;
CREATE SEQUENCE IF NOT EXISTS monetary_donation_seq;
CREATE SEQUENCE IF NOT EXISTS inquiry_seq;

-- If records already exist, start counting AFTER the highest existing number
-- (only done while a counter has never been used, so numbers are never reused).
DO $$
DECLARE
    called boolean;
BEGIN
    SELECT is_called INTO called FROM book_donation_seq;
    IF NOT called THEN
        PERFORM setval('book_donation_seq', COALESCE((SELECT MAX(substring(reference_no from '[0-9]+$')::int) FROM book_donations WHERE reference_no ~ '^BD-[0-9]+$'), 0) + 1, false);
    END IF;

    SELECT is_called INTO called FROM monetary_donation_seq;
    IF NOT called THEN
        PERFORM setval('monetary_donation_seq', COALESCE((SELECT MAX(substring(reference_no from '[0-9]+$')::int) FROM monetary_donations WHERE reference_no ~ '^MD-[0-9]+$'), 0) + 1, false);
    END IF;

    SELECT is_called INTO called FROM inquiry_seq;
    IF NOT called THEN
        PERFORM setval('inquiry_seq', COALESCE((SELECT MAX(substring(reference_no from '[0-9]+$')::int) FROM inquiries WHERE reference_no ~ '^INQ-[0-9]+$'), 0) + 1, false);
    END IF;
END $$;

-- Rate limiting for the public endpoints (one row per accepted attempt)
CREATE TABLE IF NOT EXISTS public_rate_limits (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket     VARCHAR(30) NOT NULL,
    ip_address VARCHAR(45) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_public_rate_limits ON public_rate_limits (bucket, ip_address, created_at);

-- Check (should list the 3 sequences and the table):
SELECT sequencename AS created FROM pg_sequences WHERE sequencename IN ('book_donation_seq','monetary_donation_seq','inquiry_seq')
UNION ALL SELECT tablename FROM pg_tables WHERE tablename = 'public_rate_limits';


