-- Extra details kept for each administrator account
ALTER TABLE admins ADD COLUMN IF NOT EXISTS gender               VARCHAR(20) NULL;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN     NOT NULL DEFAULT FALSE;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS created_by           INTEGER     NULL REFERENCES admins(id) ON DELETE SET NULL;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS deactivated_at       TIMESTAMPTZ NULL;
-- Logins made before this moment stop working (used by "sign the admin out of active sessions")
ALTER TABLE admins ADD COLUMN IF NOT EXISTS sessions_valid_after TIMESTAMPTZ NULL;

-- The audit log keeps the administrator's NAME at the time of the action, so the
-- record still reads correctly after an account is permanently removed.
ALTER TABLE activity_logs ADD COLUMN IF NOT EXISTS admin_name VARCHAR(100) NULL;
UPDATE activity_logs l SET admin_name = a.name
FROM admins a WHERE l.admin_id = a.id AND l.admin_name IS NULL;

CREATE INDEX IF NOT EXISTS idx_activity_created ON activity_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_admin   ON activity_logs (admin_id);

-- One-time links for "set a password" / "reset password" (only a hash of the link is stored)
CREATE TABLE IF NOT EXISTS admin_password_tokens (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   INTEGER      NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
    token_hash CHAR(64)     NOT NULL,
    purpose    VARCHAR(20)  NOT NULL CONSTRAINT chk_token_purpose CHECK (purpose IN ('set_password', 'reset_password')),
    expires_at TIMESTAMPTZ  NOT NULL,
    used_at    TIMESTAMPTZ  NULL,
    created_by INTEGER      NULL REFERENCES admins(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_token_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS idx_token_admin ON admin_password_tokens (admin_id);

